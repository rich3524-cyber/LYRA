-- Let EmailIntegration.apiKey be NULL, so disconnecting an integration can
-- actually remove the credential instead of merely hiding it.
--
-- Why: DELETE /api/email-integrations/[id] only set isActive: false and left
-- the stored API key in the row forever. There is no purge job anywhere in the
-- codebase (see LYRA-Data-Register.md section 5.1), so a key survived
-- indefinitely after the user had, as far as the UI showed them, removed the
-- integration. That is a reasonable expectation to violate: "Disconnect"
-- reads as "my key is gone".
--
-- This was found on 2026-11-07 while fixing the two production Klaviyo keys
-- that were stored in plaintext (section 5.4). Both rows sat
-- disconnected-but-still-plaintext between the disconnect and the reconnect,
-- which is exactly the window this closes.
--
-- Widening a NOT NULL column to nullable is backwards-compatible with the
-- currently deployed code, which never writes NULL -- so this can be applied
-- before the code that uses it ships, and in that order it must be.
--
-- Hand-written rather than generated by `prisma migrate dev`, per
-- prisma/migrations/README.md: the direct connection Prisma Migrate needs
-- (DIRECT_URL, port 5432) is not reachable from the dev machine, only the
-- pooled DATABASE_URL (6543). Apply via the Supabase SQL Editor, then fold
-- into a real migration file from an environment that can reach DIRECT_URL.
--
-- Safe to re-run: DROP NOT NULL on an already-nullable column is a no-op.

ALTER TABLE "EmailIntegration"
  ALTER COLUMN "apiKey" DROP NOT NULL;

-- Deliberately NOT backfilling existing inactive rows to NULL here. At the
-- time of writing both production rows are active and legitimately hold an
-- encrypted key; clearing credentials is the disconnect route's job, taken on
-- an explicit user action, not a migration's.
